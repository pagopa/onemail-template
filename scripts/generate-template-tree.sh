#!/usr/bin/env bash
# Purpose: Regenerate the managed templates tree in docs/templates-tree.md and in the README section
#          delimited by the TEMPLATE-TREE markers.
# Usage (run from the repository root):
#   bash scripts/generate-template-tree.sh          # update docs/templates-tree.md and README.md
#   bash scripts/generate-template-tree.sh --check  # fail if either file is out of date
set -euo pipefail

mode=write
case ${1-} in
    '') ;;
    --check) mode=check ;;
    *) printf 'Usage: %s [--check]\n' "$0" >&2; exit 1 ;;
esac

doc_file=docs/templates-tree.md
readme_file=README.md
start_marker='<!-- TEMPLATE-TREE:START -->'
end_marker='<!-- TEMPLATE-TREE:END -->'
pattern='^templates/([a-z][a-z0-9]*(-[a-z0-9]+)*)/([a-z][a-z0-9]*(-[a-z0-9]+)*)/(v[1-9][0-9]*)/template\.json$'

[[ -d templates ]] || { printf '❌ Run from the repository root.\n' >&2; exit 1; }
grep -qxF "$start_marker" "$readme_file" && grep -qxF "$end_marker" "$readme_file" ||
    { printf '❌ %s must contain the %s and %s markers.\n' "$readme_file" "$start_marker" "$end_marker" >&2; exit 1; }

# Collect "<client> <template-id>" pairs only from paths that follow the repository convention.
entries=()
while IFS= read -r path; do
    if [[ $path =~ $pattern ]]; then
        entries+=("${BASH_REMATCH[1]} ${BASH_REMATCH[1]}_${BASH_REMATCH[3]}_${BASH_REMATCH[5]}")
    else
        printf '⚠️  Skipping non-conforming path: %s\n' "$path" >&2
    fi
done < <(find templates -type f -name template.json | LC_ALL=C sort)

tree=$(
    if [[ ${#entries[@]} -eq 0 ]]; then
        printf '(no templates)\n'
    else
        printf '%s\n' "${entries[@]}" | LC_ALL=C sort -u | awk '
            $1 != client { if (NR > 1) print ""; client = $1; print client }
            { print "|--" $2 }
        '
    fi
)
clients=$(printf '%s\n' "${entries[@]+"${entries[@]}"}" | awk 'NF { print $1 }' | sort -u | grep -c . || true)

section=$(printf '_%s clients, %s templates. Generated by `scripts/generate-template-tree.sh`: do not edit manually._\n\n```text\n%s\n```' \
    "$clients" "${#entries[@]}" "$tree")
doc_content=$(printf '# Managed templates\n\nTemplate identifiers (`TemplateName`, used by clients as OneMail `templateId`) grouped by client.\n\n%s' "$section")

# Replace everything between the README markers, keeping the markers themselves.
readme_content=$(SECTION="$section" awk -v start="$start_marker" -v end="$end_marker" '
    $0 == start { print; print ""; print ENVIRON["SECTION"]; print ""; skip = 1; next }
    $0 == end { skip = 0 }
    !skip { print }
' "$readme_file")

if [[ $mode == check ]]; then
    stale=0
    [[ -f $doc_file && $(cat "$doc_file") == "$doc_content" ]] || { printf '❌ %s is out of date.\n' "$doc_file" >&2; stale=1; }
    [[ $(cat "$readme_file") == "$readme_content" ]] || { printf '❌ %s template tree is out of date.\n' "$readme_file" >&2; stale=1; }
    [[ $stale -eq 0 ]] && printf '✅ Template tree is up to date.\n'
    exit "$stale"
fi

printf '%s\n' "$doc_content" > "$doc_file"
printf '%s\n' "$readme_content" > "$readme_file"
printf '✅ Updated %s and %s (%s clients, %s templates).\n' "$doc_file" "$readme_file" "$clients" "${#entries[@]}"
